"""Offline parity oracle for the preserved Kotlin four-point detector.

Translated from PaperProcessor.kt at 4e2f3cd9, without the later Dart changes.
Requires numpy and opencv-python-headless; neither is an app dependency.
Reads PNGs exported by the recognition regression tests and emits Dart fixtures.
"""
import argparse
import json
from pathlib import Path

import cv2
import numpy as np


def cross(a, b):
    return float(a[0] * b[1] - b[0] * a[1])


def area(points):
    return abs(sum(cross(points[i], points[(i + 1) % 4])
                   for i in range(4))) / 2


def valid(points):
    return (np.isfinite(points).all() and (points >= 0).all()
            and (points <= 1).all() and area(points) >= .005
            and all(np.linalg.norm(points[i] - points[(i + 1) % 4]) > .01
                    and cross(points[(i + 1) % 4] - points[i],
                              points[(i + 2) % 4] - points[(i + 1) % 4]) > .00001
                    for i in range(4)))


def detect_document(image, previous=None, max_edge=960):
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    scale = min(1., max_edge / max(gray.shape))
    if scale < 1:
        gray = cv2.resize(gray, None, fx=scale, fy=scale, interpolation=cv2.INTER_AREA)
    gray = cv2.GaussianBlur(gray, (5, 5), 0)
    height, width = gray.shape
    _, mask = cv2.threshold(gray, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    dx = cv2.convertScaleAbs(cv2.Sobel(gray, cv2.CV_16S, 1, 0))
    dy = cv2.convertScaleAbs(cv2.Sobel(gray, cv2.CV_16S, 0, 1))
    gradients = np.minimum(255, dx.astype(np.int32) + dy.astype(np.int32))
    histogram = np.bincount(gradients.ravel(), minlength=256)
    threshold = float(np.clip(np.searchsorted(np.cumsum(histogram),
                                             int(gray.size * .85)) * 1.5, 24, 160))
    edges = cv2.Canny(gray, max(8, threshold * .4), threshold)
    best = None
    for proposal in (edges, mask):
        closed = cv2.morphologyEx(proposal, cv2.MORPH_CLOSE,
                                 cv2.getStructuringElement(cv2.MORPH_RECT, (3, 3)))
        contours, _ = cv2.findContours(closed, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
        for contour in sorted(contours, key=cv2.contourArea, reverse=True)[:30]:
            relative_area = cv2.contourArea(contour) / gray.size
            if not .06 <= relative_area <= .97:
                continue
            perimeter = cv2.arcLength(contour, True)
            for epsilon in (.015, .025, .04):
                raw = cv2.approxPolyDP(contour, perimeter * epsilon, True).reshape(-1, 2)
                if len(raw) != 4:
                    continue
                center = raw.mean(axis=0)
                ordered = sorted(raw, key=lambda p: np.arctan2(p[1] - center[1], p[0] - center[0]))
                start = int(np.argmin([p.sum() for p in ordered]))
                points = np.clip(np.array([ordered[(start + i) % 4] for i in range(4)],
                                         dtype=float) / (width - 1, height - 1), 0, 1)
                if not valid(points):
                    continue
                if sum((p < .005).any() or (p > .995).any() for p in points) > 2:
                    continue
                pixel_points = points * (width - 1, height - 1)
                hits = 0
                for side in range(4):
                    a, b = pixel_points[side], pixel_points[(side + 1) % 4]
                    for step in range(1, 33):
                        x, y = np.floor(a + (b - a) * (step / 33.) + .5).astype(int)
                        region = edges[max(0, y - 3):min(height, y + 4),
                                       max(0, x - 3):min(width, x + 4)]
                        hits += bool(np.any(region))
                support = hits / 128
                if support < .35:
                    continue
                quad_area = area(points)
                rectangularity = min(relative_area, quad_area) / max(relative_area, quad_area)
                agreement = .5 if previous is None else max(
                    0., 1. - np.linalg.norm(previous - points, axis=1).max() / .15)
                score = support * .5 + rectangularity * .2 + np.sqrt(quad_area) * .2 + agreement * .1
                if score > (.52 if best is None else best['confidence']):
                    best = dict(points=points.tolist(), confidence=float(score))
    return best


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('fixtures', type=Path)
    parser.add_argument('--dart-output', type=Path)
    args = parser.parse_args()
    results = {p.stem: detect_document(cv2.imread(str(p)))
               for p in sorted(args.fixtures.glob('*.png'))}
    print(json.dumps(results, indent=2))
    if args.dart_output:
        lines = ["// Generated by tools/scanner_detection/reference_detector.py.",
                 "// Oracle: preserved native detector at 4e2f3cd9 (960px, Gaussian 5).",
                 "import 'dart:ui';", "", "const nativeRecognitionCorners = <String, List<Offset>?>{"]
        for name, result in results.items():
            if result is None:
                lines.append(f"  '{name}': null,")
            else:
                corners = ', '.join(f'Offset({x:.12f}, {y:.12f})' for x, y in result['points'])
                lines.append(f"  '{name}': [{corners}],")
        lines.extend(['};', ''])
        args.dart_output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
